from orochi.base.core import OrochiBase
import py3Dmol
import json

import numpy as np
from orochi.base.core import OrochiBase
from orochi.view.params import model_viewer as default


class ModelViewer(OrochiBase):
    r"""
    A viewer class for displaying structural models using `py3Dmol` within the Orochi framework.

    This class facilitates the visualization of atomic structures,
    including unit cells and interatomic bonds, by leveraging the
    `py3Dmol` library. It integrates with Orochi's parameter management
    system to configure display properties and structural data,
    making it suitable for visualizing structures generated or
    managed within Orochi workflows (e.g., from `orochi.phase` objects).

    The viewer takes a structural model (typically from an ``orochi.phase.Phase``
    object) and renders it as an interactive 3D view, allowing for
    customization of styles, camera angles, and bond representation.

    Attributes
    ----------
    camera_position : dict
        Initial camera position for the 3D view (keys: 'x', 'y', 'z').
    center : dict
        The point the camera focuses on (keys: 'x', 'y', 'z').
    up : dict
        The 'up' direction vector for the camera (keys: 'x', 'y', 'z').
    zoom : float
        Initial zoom level of the viewer.
    duration : int
        Animation duration in milliseconds for view transitions.
    bonds_list : list of list of int or None
        A list where each inner list contains the indices of atoms bonded to the corresponding atom.
        Generated by `make_bond_list`.
    bondOrder_list : list of list of int or None
        A list where each inner list contains the bond orders corresponding to `bonds_list`.
        Defaults to [1] for each bond if not explicitly provided.
    atom_list : list of dict or None
        A list of atom dictionaries, formatted for `py3Dmol.addAtoms`.
        Each dict includes 'elem', 'x', 'y', 'z', 'bonds', 'bondOrder'.
    view : py3Dmol.view
        The `py3Dmol` viewer instance.
    model : py3Dmol.model
        The `py3Dmol` model instance associated with the viewer.
    html : str or None
        The generated HTML string for embedding the viewer, optionally wrapped in an iframe.

    See Also
    --------
    orochi.base.core.OrochiBase : Base class for parameter handling.
    py3Dmol : The underlying 3D molecular visualization library.
    orochi.view.models.params.default : Default parameters for the ModelViewer.

    """
    def __init__(self):
        """
        Initialize the `ModelViewer` class.

        Sets up default parameters for the viewer and initializes internal
        attributes for storing `py3Dmol` objects and generated data.
        """

        self._par = default.par
        self._par_key_info = default.par_key_info

        super().__init__()
        self._name = "model_viewer"
        self._id = "0"
        self.phase = None

        # Default camera settings
        self.camera_position = {'x': 0, 'y': 0, 'z': 0}
        self.center = {'x': 0, 'y': 0, 'z': 0}
        self.up = {'x': 0, 'y': 1, 'z': 0}
        self.zoom = 0
        self.duration = 0

        # Data storage for 3Dmol
        self.bonds_list = None
        self.bondOrder_list = None
        self.atom_list = None
        self.html = None


    def __call__(self):
        """
        Execute the molecular visualization pipeline.

        This method orchestrates the steps required to generate and display
        the 3D molecular model:
        1. Initializes the `py3Dmol` viewer.
        2. Adds crystal lattice data if available.
        3. Determines interatomic bonds based on a threshold.
        4. Prepares the atom data in a format suitable for `py3Dmol`.
        5. Adds atoms and applies styling.
        6. Generates the final HTML representation of the viewer.
        The resulting HTML is stored in `self.html`.
        """
        super().__call__()
        self.make_view()
        # self.set_view_style() # Commented out as per your original code
        self.add_crystal_lattice()
        self.make_bond_list()
        self.update_atom_list_for_py3dmol()
        self.add_atoms()
        self.get_html_view()


    def make_view(self):
        """
        Initializes the `py3Dmol` viewer and model instances.

        The viewer's dimensions (width, height) are taken from `self.par`.
        """
        self.view = py3Dmol.view(width=self["width"], height=self["height"])
        self.view.addModel()
        self.model = self.view.getModel()

    def set_view_style(self):
        """
        Sets the camera position and view parameters for the `py3Dmol` viewer.

        Uses the `camera_position`, `center`, `up`, `zoom`, and `duration`
        attributes to configure the viewer's perspective.
        """
        self.view.setViewStyle({
            'cameraPosition': self.camera_position,
            'center': self.center,       
            'up': self.up,               
            'zoom': self.zoom,           
            'duration': self.duration    
        })
        self.view.render()

    def add_crystal_lattice(self):
        """
        Adds crystal lattice information to the `py3Dmol` model.

        Lattice parameters are retrieved from `self.par["phase"]["lattice"]`.
        A default unit cell box and labels are also added for visualization.
        """
        if np.sum(self.phase["pbc"]) == 0:
            return
        
        lattice = self.phase.model["lattice"]
        self.model.setCrystData(*lattice)
        self.view.addUnitCell({'box': {'color': 'purple'}, 'alabel': 'X', 'blabel': 'Y', 'clabel': 'Z',
                                'alabelstyle': {'fontColor': 'black', 'backgroundColor': 'white', 'inFront': True,
                                                'fontSize': 40},
                                'astyle': {'color': 'darkred', 'radius': 5, 'midpos': -10}})


    def make_bond_list(self):
        """
        Generates a list of bonded atom indices based on a distance threshold.

        Uses the `get_bond_relationship` method of the `orochi.phase.Phase`
        object with the `bond_threshold` from `self.par`.
        The result is stored in `self.bonds_list`.
        """
        phase = self.phase
        self.bonds_list = phase.get_bond_relationship(self["bond_threshold"])

    def update_atom_list_for_py3dmol(self):
        """
        Prepares and updates the list of atom data for `py3Dmol` visualization.

        Converts fractional coordinates from the `orochi.phase.Phase` object
        to Cartesian coordinates and integrates bond information (`bonds_list`,
        `bondOrder_list`) into the atom dictionaries.
        If `bondOrder_list` is not provided, it defaults to single bonds (order 1).
        The final list is stored in `self.atom_list`.

        Returns
        -------
        list of dict
            The formatted list of atom dictionaries.
        """
        phase = self.phase
        symbol = phase.model["symbol"]
        g = phase.model["lattice_vector"].T
        xyz = np.dot(g, phase.model["xyz"].T).T

        atom_list = []
        for n, s in enumerate(symbol):
            x, y, z = xyz[n]
            if self.bonds_list is not None:
                bonds = self.bonds_list[n]
                if self.bondOrder_list is not None:
                    bondOrder = self.bondOrder_list[n]
                else:
                    bondOrder = len(bonds) * [1]
            else:
                bonds = []
                bondOrder = []
            atom_list.append({'elem': str(s),
                              'x': float(x),
                              'y': float(y),
                              'z': float(z),
                              'bonds': bonds,
                              'bondOrder': bondOrder})

        self.atom_list = atom_list
        return atom_list

    @staticmethod
    def make_atom_list_for_py3dmol(symbol:list, xyz:list, bonds_list=None, bondOrder_list=None):
        """
        Static method to create a list of atom data for `py3Dmol` from raw data.

        This utility function formats elemental symbols, Cartesian coordinates,
        and optionally bond information into a list of dictionaries suitable
        for `py3Dmol.addAtoms`. If `bondOrder_list` is not provided, it
        defaults to single bonds (order 1).

        Parameters
        ----------
        symbol : list
            List of elemental symbols (e.g., ['Ce', 'O']).
        xyz : list
            List of Cartesian coordinates for each atom (e.g., [[x1,y1,z1], [x2,y2,z2]]).
        bonds_list : list of list of int, optional
            List of bond indices for each atom. Defaults to None (no bonds).
        bondOrder_list : list of list of int, optional
            List of bond orders for each bond. Defaults to None (all bonds order 1).

        Returns
        -------
        list of dict
            The formatted list of atom dictionaries.
        """
        atom_list = []
        for n, s in enumerate(symbol):
            x, y, z = xyz[n]
            if bonds_list is not None:
                bonds = bonds_list[n]
                if bondOrder_list is not None:
                    bondOrder = bondOrder_list[n]
                else:
                    bondOrder = len(bonds) * [1]
            else:
                bonds = []
                bondOrder = []
            atom_list.append({'elem': s, 'x': x, 'y': y, 'z': z, 'bonds': bonds, 'bondOrder': bondOrder})
        return atom_list

    def add_atoms(self):
        """
        Adds the prepared atom list to the `py3Dmol` model and applies styling.

        Uses `self.atom_list` to add atoms and sets default `stick` and `sphere`
        styles for visualization. The viewer is then zoomed to fit the model.
        """
        phase = self.phase
        phase._clear_changed_parameters() # Ensure parameters are clean for the phase object
        self.model.addAtoms(self.atom_list)
        self.model.setStyle({'stick': {'radius': 0.2, 'opacity': 1},
                              'sphere': {'scale': 0.3, 'colorscheme': 'jmol', 'opacity': 1}})
        self.view.zoomTo()

    def get_html_view(self, iframe=True):
        """
        Generates the HTML representation of the `py3Dmol` viewer.

        Optionally wraps the generated HTML in an `iframe` for embedding,
        which is particularly useful for Gradio integration. The dimensions
        of the iframe are taken from `self.par["width"]` and `self.par["height"]`.
        The HTML string is stored in `self.html`.

        Parameters
        ----------
        iframe : bool, optional
            If True, the HTML is wrapped in an iframe. Defaults to True.
        """
        html_content = self.view._make_html()
        if iframe:
            # Escape single quotes for srcdoc attribute
            escaped_html_string = html_content.replace("'", "&#x27;")
            # Ensure width/height in iframe tag have units if not already in self.par
            iframe_html = f"""<iframe srcdoc=\'{escaped_html_string}\' width="{self['width']}" height="{self['height']}" frameborder="0" allowfullscreen sandbox="allow-scripts allow-same-origin"></iframe>"""
            self.html = iframe_html
        else:
            self.html = html_content